interface dns_resolver {
    /**
     * Resolve a host name to its A and AAAA addresses.
     *
     * @param string $host Host name.
     * @return string[]|null Addresses (possibly empty for NXDOMAIN), or null when the lookup itself failed.
     */
    public function resolve(string $host): ?array;
}
